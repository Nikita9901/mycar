// Абстрактный репозиторий для сущности Car.
// Domain слой определяет КОНТРАКТ — что умеет репозиторий.
// Реализацию предоставляет Data слой (CarRepositoryImpl).

import '../entities/car.dart';

/// Контракт репозитория автомобилей.
///
/// Use Cases зависят от этого абстрактного класса, а не от конкретной
/// реализации. Это позволяет подменять реализацию (например, для тестов).
abstract class CarRepository {
  /// Получить список всех автомобилей пользователя.
  Future<List<Car>> getAllCars();

  /// Получить автомобиль по его идентификатору.
  /// Возвращает [null], если автомобиль не найден.
  Future<Car?> getCarById(String carId);

  /// Добавить новый автомобиль.
  Future<void> addCar(Car car);

  /// Обновить данные существующего автомобиля.
  Future<void> updateCar(Car car);

  /// Обновить текущий одометр автомобиля.
  ///
  /// Вынесено отдельно, так как обновление пробега —
  /// очень частая операция (при каждой заправке).
  Future<void> updateOdometer(String carId, int newOdometer);

  /// Удалить автомобиль и все связанные записи (каскадно).
  Future<void> deleteCar(String carId);

  /// Поток всех автомобилей — реагирует на изменения в БД.
  /// Используется для реактивного обновления UI.
  Stream<List<Car>> watchAllCars();
}
